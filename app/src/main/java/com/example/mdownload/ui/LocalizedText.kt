    "Discard" to "Bỏ thay đổi",
    "Keep editing" to "Tiếp tục sửa",
)
fun translateText(text:String, isVietnamese:Boolean):String {
    if(!isVietnamese) return text
    vietnamese[text]?.let { return it }
    if(text.matches(Regex("""Queue \(\d+\)"""))) return "Hàng đợi " + text.substringAfter("Queue ")
    if(text.matches(Regex("""History \(\d+\)"""))) return "Lịch sử " + text.substringAfter("History ")
    if(text.matches(Regex("""Add \(\d+\)"""))) return "Thêm " + text.substringAfter("Add ")
    if(text.matches(Regex("""Save \(\d+\)"""))) return "Lưu " + text.substringAfter("Save ")
    if(text.matches(Regex("""\d+ artist\(s\)"""))) return text.replace(" artist(s)", " nghệ sĩ")
    if(text.startsWith("Saved artist \"")) return "Đã lưu nghệ sĩ " + text.removePrefix("Saved artist ")
    if(text.startsWith("Updated artist \"")) return "Đã cập nhật nghệ sĩ " + text.removePrefix("Updated artist ")
    if(text.startsWith("Removed artist \"")) return "Đã xóa nghệ sĩ " + text.removePrefix("Removed artist ")
    if(text.startsWith("Updated songs for \"")) return "Đã cập nhật bài hát cho " + text.removePrefix("Updated songs for ")
    if(text.startsWith("Restored original artist for \"")) return "Đã khôi phục nghệ sĩ gốc cho " + text.removePrefix("Restored original artist for ")
    if(text.startsWith("Assigned \"") && text.contains("\" to \"")) return "Đã gán " + text.removePrefix("Assigned ").replace("\" to \"", "\" cho \"")
    if(text.matches(Regex("""Download \(\d+\)"""))) return "Tải " + text.substringAfter("Download ")
    if(text.matches(Regex("""\d+ custom playlist\(s\)"""))) return text.replace(" custom playlist(s)", " danh sách phát tùy chỉnh")
    if(text.matches(Regex("""\d+ track\(s\)"""))) return text.replace(" track(s)", " bài")
    if(text.matches(Regex("""\d+ track\(s\) · Added"""))) return text.replace(" track(s) · Added", " bài · Đã thêm")
    if(text.matches(Regex("""\d+ album\(s\) · \d+ track\(s\)"""))) return text.replace(" album(s) · ", " album · ").replace(" track(s)", " bài")
    if(text.startsWith("Download folder: ")) return "Thư mục tải: " + text.removePrefix("Download folder: ")
    if(text.startsWith("Will play \"") && text.endsWith("\" next.")) return "Sẽ phát tiếp theo: " + text.removePrefix("Will play ").removeSuffix(" next.")
    if(text.startsWith("Added \"") && text.endsWith("\" to Favorites.")) return "Đã thêm " + text.removePrefix("Added ").removeSuffix(" to Favorites.") + " vào Yêu thích."
    if(text.startsWith("Removed \"") && text.endsWith("\" from Favorites.")) return "Đã bỏ " + text.removePrefix("Removed ").removeSuffix(" from Favorites.") + " khỏi Yêu thích."
    if(text.startsWith("Added \"") && text.endsWith("\" to playing queue.")) return "Đã thêm " + text.removePrefix("Added ").removeSuffix(" to playing queue.") + " vào hàng phát."
    if(text.startsWith("Added \"") && text.endsWith("\" to playlist.")) return "Đã thêm " + text.removePrefix("Added ").removeSuffix(" to playlist.") + " vào danh sách phát."
    if(text.startsWith("Created playlist \"")) return "Đã tạo danh sách phát " + text.removePrefix("Created playlist ")
    if(text.matches(Regex("""\d+ links"""))) return text.replace(" links", " liên kết")
    if(text.matches(Regex("""\d+ links detected"""))) return text.replace(" links detected", " liên kết được nhận diện")
    if(text.matches(Regex("""\d+ failed track\(s\)"""))) return text.replace(" failed track(s)", " bài bị lỗi")
    if(text.matches(Regex("""Paused · \d+ track\(s\) waiting"""))) return text.replace("Paused · ", "Đang tạm dừng · ").replace(" track(s) waiting", " bài đang chờ")
    if(text.startsWith("Retrying ") && text.contains(" failed track(s)")) return "Đang thử lại " + text.removePrefix("Retrying ").replace(" failed track(s)", " bài lỗi")
    if(text.matches(Regex("""\d+ shared media links"""))) return text.replace(" shared media links", " liên kết đã chia sẻ")
    if(text.startsWith("Downloading \"")) return "Đang tải " + text.removePrefix("Downloading ")
    if(text.startsWith("Downloading ") && text.contains(" track(s)")) return "Đang tải " + text.removePrefix("Downloading ").replace(" track(s)", " bài")
    if(text.startsWith("Queued ") && text.contains(" track(s)")) return "Đã xếp hàng " + text.removePrefix("Queued ").replace(" track(s)", " bài")
    if(text.startsWith("Added \"")) return "Đã thêm " + text.removePrefix("Added ").replace(" to queue.", " vào hàng đợi.")
    if(text.startsWith("Saved: ")) return "Đã lưu: " + text.removePrefix("Saved: ")
    if(text.startsWith("Synced ")) return "Đã đồng bộ " + text.removePrefix("Synced ").replace(" track(s) from ", " bài từ ")
    if(text.startsWith("Folder: ")) return "Thư mục: " + text.removePrefix("Folder: ")
    if(text.startsWith("Already downloaded: ")) return "Đã tải trước đó: " + text.removePrefix("Already downloaded: ")
    if(text.startsWith("Already in queue: ")) return "Đã có trong hàng đợi: " + text.removePrefix("Already in queue: ")
    if(text.startsWith("Preview unavailable: ")) return "Không lấy được bản xem trước: " + text.removePrefix("Preview unavailable: ")
    return text
}
@Composable fun localText(text:String):String = translateText(text, LocalConfiguration.current.locales[0].language == "vi")

@Composable
fun AppText(text:String, modifier:Modifier=Modifier, color:Color=Color.Unspecified,
    fontSize:TextUnit=TextUnit.Unspecified, fontStyle:FontStyle?=null, fontWeight:FontWeight?=null,
    fontFamily:FontFamily?=null, letterSpacing:TextUnit=TextUnit.Unspecified,
    textDecoration:TextDecoration?=null, textAlign:TextAlign?=null,
    lineHeight:TextUnit=TextUnit.Unspecified, overflow:TextOverflow=TextOverflow.Clip,
    softWrap:Boolean=true, maxLines:Int=Int.MAX_VALUE, minLines:Int=1,
    style:TextStyle=LocalTextStyle.current) {
    androidx.compose.material3.Text(text=localText(text), modifier=modifier, color=color, fontSize=fontSize,
        fontStyle=fontStyle, fontWeight=fontWeight, fontFamily=fontFamily, letterSpacing=letterSpacing,
        textDecoration=textDecoration, textAlign=textAlign, lineHeight=lineHeight, overflow=overflow,
        softWrap=softWrap, maxLines=maxLines, minLines=minLines, style=style)
}
